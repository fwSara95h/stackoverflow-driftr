#!/usr/bin/env python3
"""Regenerate the chapter READMEs and the index section of the top-level README from the front matter in this repository.

Run from the repository root (or pass it): python3 tools/build_index.py [repo_root]

Reads every <chapter>/<question folder>/question.md, my-answer*.md and other-answer-*.md, counts code files, and writes
<chapter>/README.md (full file) and the part of README.md between <!-- index:start --> and <!-- index:end -->.
Chapter titles and introductions come from tools/chapters.json. No network, no dependencies.
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.getcwd())
HERE = os.path.dirname(os.path.abspath(__file__))
CHAPTERS = json.load(open(os.path.join(HERE, "chapters.json"), encoding="utf-8"))
CODE_EXT = (".py", ".js", ".html", ".json", ".sh", ".txt", ".css", ".sql", ".r", ".ts")


def front_matter(path):
    fm = {}
    try:
        with open(path, encoding="utf-8") as f:
            first = f.readline()
            if first.strip() != "---":
                return fm
            for line in f:
                if line.strip() == "---":
                    break
                m = re.match(r"^([A-Za-z_][\w]*):\s?(.*)$", line.rstrip("\n"))
                if m:
                    k, v = m.group(1), m.group(2).strip()
                    if v.startswith('"') and v.endswith('"'):
                        try:
                            v = json.loads(v)
                        except ValueError:
                            v = v[1:-1]
                    fm[k] = v
    except OSError:
        pass
    return fm


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def yes(v):
    return "yes" if str(v).lower() in ("true", "yes") else "no"


chapters = []
for ch_dir in sorted(d for d in os.listdir(ROOT) if re.match(r"^[A-Z]\d*-", d) and os.path.isdir(os.path.join(ROOT, d))):
    code = ch_dir.split("-", 1)[0]
    meta = CHAPTERS.get(code, {"title": ch_dir, "intro": ""})
    rows = []
    for qdir in sorted(d for d in os.listdir(os.path.join(ROOT, ch_dir)) if os.path.isdir(os.path.join(ROOT, ch_dir, d))):
        qpath = os.path.join(ROOT, ch_dir, qdir)
        q = front_matter(os.path.join(qpath, "question.md"))
        if not q:
            continue
        answers = sorted(glob.glob(os.path.join(qpath, "my-answer*.md")))
        others = sorted(glob.glob(os.path.join(qpath, "other-answer-*.md")))
        a = front_matter(answers[0]) if answers else {}
        code_files = sorted(os.path.basename(p) for p in glob.glob(os.path.join(qpath, "*")) if p.lower().endswith(CODE_EXT) and os.path.basename(p) not in ("README.md",))
        rows.append({
            "dir": qdir, "title": q.get("title", qdir), "url": q.get("url", ""), "asked": q.get("asked", "")[:10], "site": q.get("site", ""),
            "answered": a.get("answered", "")[:10], "accepted": yes(a.get("accepted", "false")), "score": a.get("score", ""),
            "n_mine": len(answers), "n_others": len(others), "code": code_files, "views": q.get("views_at_snapshot", ""),
            "status": a.get("status", ""),
        })
    rows.sort(key=lambda r: r["answered"] or r["asked"])
    chapters.append({"code": code, "dir": ch_dir, "title": meta["title"], "intro": meta.get("intro", ""), "rows": rows})
    lines = [f"# {code} — {meta['title']}", ""]
    if meta.get("intro"):
        lines += [meta["intro"], ""]
    acc = sum(1 for r in rows if r["accepted"] == "yes")
    n_code = sum(1 for r in rows if r["code"])
    lines += [f"{len(rows)} questions · {acc} accepted · {sum(r['n_others'] for r in rows)} answers by others kept as context · code extracted for {n_code}. Sorted by the day I answered, newest last.", "",
              "| Question | Asked | Answered | Accepted | Score | Other answers | Code |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        code_links = ", ".join(f"[{c}]({r['dir']}/{c})" for c in r["code"]) or "—"
        site = "" if r["site"] in ("", "stackoverflow") else f" ({r['site']})"
        lines.append(f"| [{esc(r['title'])}]({r['dir']}/question.md){site} | {r['asked']} | [{r['answered']}]({r['dir']}/my-answer.md) | {r['accepted']} | {r['score']} | {r['n_others']} | {code_links} |")
    with open(os.path.join(ROOT, ch_dir, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

# top-level index section
total = sum(len(c["rows"]) for c in chapters)
total_acc = sum(1 for c in chapters for r in c["rows"] if r["accepted"] == "yes")
total_mine = sum(r["n_mine"] for c in chapters for r in c["rows"])
total_others = sum(r["n_others"] for c in chapters for r in c["rows"])
idx = ["<!-- index:start -->", f"{total} questions · {total_mine} answers by me · {total_acc} accepted · {total_others} answers by others kept as context. Generated by `tools/build_index.py`; each chapter folder has its own README with one row per question.", "",
       "| Chapter | Questions | Accepted | Answers by others | With code |", "| --- | --- | --- | --- | --- |"]
for c in chapters:
    idx.append(f"| [{c['code']} — {esc(c['title'])}]({c['dir']}/README.md) | {len(c['rows'])} | {sum(1 for r in c['rows'] if r['accepted'] == 'yes')} | {sum(r['n_others'] for r in c['rows'])} | {sum(1 for r in c['rows'] if r['code'])} |")
idx.append("<!-- index:end -->")
readme = os.path.join(ROOT, "README.md")
if os.path.exists(readme):
    text = open(readme, encoding="utf-8").read()
    if "<!-- index:start -->" in text and "<!-- index:end -->" in text:
        pre = text[: text.index("<!-- index:start -->")]
        post = text[text.index("<!-- index:end -->") + len("<!-- index:end -->"):]
        text = pre + "\n".join(idx) + post
    else:
        text = text.rstrip("\n") + "\n\n## Index\n\n" + "\n".join(idx) + "\n"
    with open(readme, "w", encoding="utf-8") as f:
        f.write(text)
print(f"{len(chapters)} chapters, {total} questions, {total_mine} answers by me, {total_others} by others; chapter READMEs and the README index regenerated")
